    .global _start
    .section text
_start:
.text
    # --------------------------------------------------------
    # A = 0x80400000
    # size = 0x300000 bytes
    # end/result = 0x80700000
    #
    # r12 : 当前数组指针
    # r15 : 数组结束地址 / 结果地址
    # r13 : target = A[0]
    # r8-r11 : 4 个读取值 / 比较结果
    # r16-r19 : 4 个独立计数器
    # --------------------------------------------------------

    lu12i.w   $r12, -523264          # r12 = 0x80400000
    lu12i.w   $r15, -522496          # r15 = 0x80700000

    ld.w       $r13, $r12, 0         # target = A[0]

    or         $r16, $r0, $r0        # count0 = 0
    or         $r17, $r0, $r0        # count1 = 0
    or         $r18, $r0, $r0        # count2 = 0
    or         $r19, $r0, $r0        # count3 = 0

    .align 4,54525952,4

.L3:
    # 每轮处理 4 个 32 位整数
    ld.w       $r8,  $r12, 0
    ld.w       $r9,  $r12, 4
    ld.w       $r10, $r12, 8
    ld.w       $r11, $r12, 12

    # --------------------------------------------------------
    # 判断 value == target
    #
    # value ^ target:
    #   相等   -> 0
    #   不相等 -> 非0
    #
    # sltui x,x,1:
    #   x == 0 -> 1
    #   x != 0 -> 0
    # --------------------------------------------------------

    xor        $r8,  $r8,  $r13
    xor        $r9,  $r9,  $r13
    xor        $r10, $r10, $r13
    xor        $r11, $r11, $r13

    sltui      $r8,  $r8,  1
    sltui      $r9,  $r9,  1
    sltui      $r10, $r10, 1
    sltui      $r11, $r11, 1

    # 四个独立计数器
    add.w      $r16, $r16, $r8
    add.w      $r17, $r17, $r9
    add.w      $r18, $r18, $r10
    add.w      $r19, $r19, $r11

    # 一轮处理 4 * 4 = 16 Byte
    addi.w     $r12, $r12, 16

    # 到 0x80700000 时结束
    bne        $r12, $r15, .L3

    # --------------------------------------------------------
    # 合并四个部分计数器
    # --------------------------------------------------------

    add.w      $r16, $r16, $r17
    add.w      $r18, $r18, $r19
    add.w      $r14, $r16, $r18

    # --------------------------------------------------------
    # result address = 0x80700000
    # --------------------------------------------------------

    st.w       $r14, $r15, 0

    # 保留原模板返回方式
    or         $r4, $r0, $r0
    jr         $r1