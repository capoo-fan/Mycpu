`default_nettype none

// ============================================================================
// accelerator_logic.v
//
// Map 型加速器的【比赛算法逻辑区】
//
// 固定接口：
//     in_valid + in_ready  : engine 提交一个输入元素
//     out_valid + out_data : 算法返回一个输出元素
//
// 语义：
//     out_data = F(in_data)
//
// IMPORTANT:
//   1. array_map_engine.v 负责数组遍历和访存，本文件不要访问 SRAM。
//   2. 比赛现场主要修改本文件中的 USER MODIFY REGION。
//   3. 必须保证：每接受 1 个输入，最终恰好产生 1 个 out_valid。
//   4. 当前默认例子是“原样返回”，保证模板本身可以编译和联调。
// ============================================================================

module accelerator_logic (
    input  wire        clk,
    input  wire        resetn,

    input  wire        in_valid,
    output wire        in_ready,
    input  wire [31:0] in_data,

    output reg         out_valid,
    output reg  [31:0] out_data
);

    // =========================================================================
    // FIXED HANDSHAKE SHELL
    //
    // 一次只处理一个元素。
    // 如果将来做流水化算法，可以保留外部接口，仅重写本文件内部。
    // =========================================================================

    reg        working;
    reg [31:0] work_data;

    assign in_ready = !working;


    // =========================================================================
    // >>>>>>>>>>>>>>>>>>> USER MODIFY REGION 1 BEGIN <<<<<<<<<<<<<<<<<<<<<<<<<<
    //
    // 算法需要的状态寄存器写在这里。
    //
    // 示例：
    // reg [31:0] acc;
    // reg [4:0]  iter;
    //
    // 对简单组合/单拍算法，可以一个额外寄存器都不加。
    // =========================================================================

    // USER ALGORITHM REGISTERS HERE


    // =========================================================================
    // >>>>>>>>>>>>>>>>>>> USER MODIFY REGION 1 END <<<<<<<<<<<<<<<<<<<<<<<<<<<<
    // =========================================================================


    always @(posedge clk) begin
        if (!resetn) begin
            working   <= 1'b0;
            work_data <= 32'b0;

            out_valid <= 1'b0;
            out_data  <= 32'b0;

            // =================================================================
            // >>>>>>>>> USER MODIFY REGION 2: RESET BEGIN <<<<<<<<<<<<<<<<<<<<
            //
            // 用户算法寄存器复位
            // =================================================================

            // USER RESET HERE

            // =================================================================
            // >>>>>>>>> USER MODIFY REGION 2: RESET END <<<<<<<<<<<<<<<<<<<<<<
            // =================================================================
        end
        else begin
            // 默认输出 valid 只维持 1 拍
            out_valid <= 1'b0;

            // -----------------------------------------------------------------
            // 接受新输入
            // -----------------------------------------------------------------
            if (in_valid && in_ready) begin
                work_data <= in_data;
                working   <= 1'b1;

                // =============================================================
                // >>>>>>> USER MODIFY REGION 3: START BEGIN <<<<<<<<<<<<<<<<<<
                //
                // 新元素进入时，初始化本元素的算法状态。
                //
                // 当前默认算法无需额外初始化。
                //
                // 示例：
                //   sqrt_radicand <= in_data;
                //   iter          <= 0;
                //
                // =============================================================

                // USER START LOGIC HERE

                // =============================================================
                // >>>>>>> USER MODIFY REGION 3: START END <<<<<<<<<<<<<<<<<<<<
                // =============================================================
            end

            // -----------------------------------------------------------------
            // 当前正在计算
            // -----------------------------------------------------------------
            else if (working) begin

                // =============================================================
                // >>>>>>> USER MODIFY REGION 4: CALCULATE BEGIN <<<<<<<<<<<<<<<
                //
                // ★ 比赛现场最主要修改的位置 ★
                //
                // 必须在算法完成时：
                //
                //   out_data  <= 最终结果;
                //   out_valid <= 1'b1;
                //   working   <= 1'b0;
                //
                // -------------------------------------------------------------
                // 当前默认示例：identity
                //
                //   F(x) = x
                //
                // 也就是读到什么就原样写回。
                // -------------------------------------------------------------

                out_data  <= work_data;
                out_valid <= 1'b1;
                working   <= 1'b0;

                // =============================================================
                // >>>>>>> USER MODIFY REGION 4: CALCULATE END <<<<<<<<<<<<<<<<<
                // =============================================================
            end
        end
    end

endmodule

`default_nettype wire
